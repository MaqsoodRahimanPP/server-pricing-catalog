"use strict";

const express = require("express");
const router = express.Router();

// POST /api/reports/export
router.post("/export", (req, res) => {
  const {
    projectName = "Cloud Infrastructure Architecture",
    requirements = {},
    selectedTier = "balanced",
    costEstimate = {},
    architecture = {},
    insights = []
  } = req.body || {};

  const generatedDate = new Date().toISOString();

  const markdownReport = `
# CloudBlueprint Architecture & FinOps Report
**Project Name:** ${projectName}
**Generated:** ${generatedDate}
**Selected Tier:** ${selectedTier.toUpperCase()}
**Estimated Monthly Cost:** $${costEstimate.totalMonthlyUSD || 0} USD ($${costEstimate.annualProjectedUSD || 0}/year)

---

## 1. Executive Summary
- **Workload Target:** ${requirements.users ? requirements.users.toLocaleString() : "10,000"} monthly active users
- **Application Instances:** ${requirements.nodes || 2} node(s) (${requirements.stack || "node"} stack)
- **High Availability:** ${requirements.availability === "ha" ? "Active (Multi-AZ)" : "Standard"}
- **Compliance Certification:** ${requirements.compliance ? "Required (SOC2 / HIPAA / ISO)" : "Standard"}

---

## 2. Infrastructure Cost Breakdown
- **Compute:** $${costEstimate.lineItems ? costEstimate.lineItems.computeUSD : 0}/mo
- **Database:** $${costEstimate.lineItems ? costEstimate.lineItems.databaseUSD : 0}/mo
- **Storage:** $${costEstimate.lineItems ? costEstimate.lineItems.storageUSD : 0}/mo
- **Bandwidth / Egress:** $${costEstimate.lineItems ? costEstimate.lineItems.transferUSD : 0}/mo
- **Networking & CDN:** $${costEstimate.lineItems ? costEstimate.lineItems.networkingUSD : 0}/mo
- **Backups & Monitoring:** $${(costEstimate.lineItems ? costEstimate.lineItems.backupUSD + costEstimate.lineItems.monitoringUSD : 0).toFixed(2)}/mo

### Usage Scenarios
- **Low Usage (-25%):** $${costEstimate.scenarios ? costEstimate.scenarios.lowUSD : 0}/mo
- **Expected Baseline:** $${costEstimate.scenarios ? costEstimate.scenarios.expectedUSD : 0}/mo
- **High Traffic (+50%):** $${costEstimate.scenarios ? costEstimate.scenarios.highUSD : 0}/mo

---

## 3. Architecture Topology & Security Boundaries
- **Components Count:** ${architecture.nodes ? architecture.nodes.length : 0} nodes
- **Security Boundaries:** Public Edge, Private VPC Application Subnet, Isolated Data Subnet
- **Network Path:** End Users -> Cloudflare CDN -> WAF -> Load Balancer -> App Cluster -> PgBouncer Pooler -> Private Database

---

## 4. Key FinOps & Security Advisory Items
${(insights || [])
  .slice(0, 5)
  .map(
    i => `### ${i.category}
- **Problem:** ${i.problem}
- **Action:** ${i.action}
- **Impact:** ${i.expectedImpact}
`
  )
  .join("\n")}

---
*Generated by CloudBlueprint 2026. Validate all architectural, sizing, and pricing assumptions on official cloud documentation before purchasing.*
`.trim();

  res.json({
    success: true,
    data: {
      projectName,
      generatedDate,
      markdownReport,
      exportJson: {
        projectName,
        generatedDate,
        requirements,
        selectedTier,
        costEstimate,
        architecture,
        insights
      }
    }
  });
});

module.exports = router;
